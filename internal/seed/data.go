// Package seed loads idempotent demo data: ten beauty brands, each with a
// catalogue of between thirty and fifty products, for demonstrating the buyer
// and sales flows at a realistic size.
//
// Everything here is invented sample data. There is no real customer data,
// and the seed never touches order requests or orders, so it cannot interfere
// with the accept-flow tests.
//
// Two conventions hold throughout, and both are load bearing:
//
//   - Names use letters, digits and spaces only. No accents, punctuation or
//     symbols, so a name survives a URL, a CSV export and a terminal without
//     escaping, and search behaves the same for everyone typing it.
//   - A workspace uses one currency for its whole catalogue. A request must
//     be single currency for its total to be meaningful, so a buyer can never
//     build an invalid basket out of seeded products.
package seed

// Product is one catalogue entry in the demo data.
type Product struct {
	Name string
	// Price is a decimal string, parsed into NUMERIC(12,2). Deliberately not
	// a float: money never passes through binary floating point.
	Price    string
	Currency string
	Stock    int32
}

// Workspace is a demo tenant and its catalogue.
type Workspace struct {
	Name string
	// Slug is stable across runs and is what makes the seed idempotent: it is
	// the conflict target when upserting the workspace.
	Slug     string
	Products []Product
}

